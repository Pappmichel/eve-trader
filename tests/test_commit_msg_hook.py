"""The commit-msg hook rejects attribution lines and accepts normal messages."""
import shutil
import subprocess
from pathlib import Path

import pytest

HOOK = Path(__file__).resolve().parents[1] / ".githooks" / "commit-msg"
SH = shutil.which("sh")

pytestmark = pytest.mark.skipif(SH is None, reason="no sh available")


def _run(tmp_path, message: str) -> subprocess.CompletedProcess:
    f = tmp_path / "msg"
    f.write_bytes(message.encode())
    return subprocess.run([SH, str(HOOK), str(f)], capture_output=True, text=True)


def test_clean_message_passes(tmp_path):
    msg = "Fix rounding in the shopping list\n\nThe cost is now summed once.\n\nCo-Authored-By: Alice <a@example.com>\n"
    assert _run(tmp_path, msg).returncode == 0


def test_comment_lines_are_ignored(tmp_path):
    assert _run(tmp_path, "Subject\n\n# Co-Authored-By: Claude <x@y>\n").returncode == 0


@pytest.mark.parametrize("line", [
    "Co-Authored-By: Claude Sonnet <noreply@anthropic.com>",
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "co-authored-by: someone <noreply@anthropic.com>",
    "Co-Authored-By: Cursor Agent <cursoragent@cursor.com>",
    "Claude-Session: https://example.invalid/session/1",
    "Generated with Claude Code",
    "Generated by Claude Code",
    "\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)",
])
def test_attribution_lines_are_rejected(tmp_path, line):
    r = _run(tmp_path, f"Subject\n\nBody text.\n\n{line}\n")
    assert r.returncode == 1
    assert "rejected" in r.stderr
